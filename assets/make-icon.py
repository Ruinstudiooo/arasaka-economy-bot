#!/usr/bin/env python3
"""
draws the bot avatar with cairo. every pixel here is a circle, a line or a glyph
from a font, nothing generated by a model.

    python3 assets/make-icon.py

writes icon-seal-1024.png, icon-wordmark-1024.png and icon-monogram-1024.png,
each also at 512 and 128, plus sheet.png with all three at the sizes discord
actually uses.
"""

import math
import os
import cairo
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))

DARK = (0.043, 0.043, 0.051)
RED = (0.784, 0.063, 0.180)
DEEP = (0.478, 0.039, 0.102)

FONT = "Noto Sans CJK SC"
BASE = 1024
SS = 2


def canvas():
    surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, BASE * SS, BASE * SS)
    ctx = cairo.Context(surface)
    ctx.scale(SS, SS)
    return surface, ctx


def background(ctx):
    ctx.set_source_rgb(*DARK)
    ctx.paint()

    glow = cairo.RadialGradient(512, 480, 30, 512, 480, 660)
    glow.add_color_stop_rgba(0, *RED, 0.15)
    glow.add_color_stop_rgba(1, *RED, 0.0)
    ctx.set_source(glow)
    ctx.paint()


def circle(ctx, cx, cy, r):
    ctx.new_sub_path()
    ctx.arc(cx, cy, r, 0, 2 * math.pi)


def glyph(ctx, char, size, cx, cy, color=DARK, weight=0.0, tracking=0.0):
    """one character centred on cx,cy. weight thickens it past the font's bold."""
    ctx.select_font_face(FONT, cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_BOLD)
    ctx.set_font_size(size)

    xb, yb, w, h, _, _ = ctx.text_extents(char)
    ctx.new_path()
    ctx.move_to(cx - w / 2 - xb, cy - h / 2 - yb)
    ctx.text_path(char)

    ctx.set_source_rgb(*color)
    ctx.set_line_join(cairo.LINE_JOIN_ROUND)
    ctx.set_line_cap(cairo.LINE_CAP_ROUND)
    if weight:
        ctx.set_line_width(weight)
        ctx.stroke_preserve()
    ctx.fill()

    return w + tracking


def rim(ctx, r_outer, r_inner, count, alpha, width, color=DEEP):
    """coin edge ticks. at 128 they read as thickness, at 64 they fade out."""
    ctx.set_source_rgba(*color, alpha)
    ctx.set_line_width(width)
    ctx.set_line_cap(cairo.LINE_CAP_BUTT)

    for i in range(count):
        a = i * (2 * math.pi / count)
        dx, dy = math.cos(a), math.sin(a)
        ctx.move_to(512 + dx * r_outer, 512 + dy * r_outer)
        ctx.line_to(512 + dx * r_inner, 512 + dy * r_inner)
        ctx.stroke()


def variant_wordmark(ctx):
    """both currency marks, big, evenly spaced across a coin"""
    circle(ctx, 512, 512, 452)
    ctx.set_source_rgba(*RED, 0.40)
    ctx.set_line_width(5)
    ctx.stroke()

    circle(ctx, 512, 512, 358)
    ctx.set_source_rgb(*RED)
    ctx.fill()

    rim(ctx, 358, 336, 72, 0.32, 6)

    circle(ctx, 512, 512, 302)
    ctx.set_source_rgba(*DEEP, 0.80)
    ctx.set_line_width(10)
    ctx.stroke()

    glyph(ctx, "€", 250, 410, 512, weight=13)
    glyph(ctx, "$", 250, 620, 512, weight=13)


def variant_seal(ctx):
    """one euro, one dollar tucked under it, coin rim outside the disc"""
    circle(ctx, 512, 512, 452)
    ctx.set_source_rgba(*RED, 0.40)
    ctx.set_line_width(5)
    ctx.stroke()

    circle(ctx, 512, 512, 372)
    ctx.set_source_rgb(*RED)
    ctx.fill()

    rim(ctx, 410, 376, 64, 0.60, 9, RED)

    circle(ctx, 512, 512, 330)
    ctx.set_source_rgba(*DEEP, 0.50)
    ctx.set_line_width(8)
    ctx.stroke()

    glyph(ctx, "€", 396, 468, 472, weight=18)
    glyph(ctx, "$", 150, 664, 648, weight=8)


def variant_monogram(ctx):
    """the letter only, for when the glyphs get too busy"""
    circle(ctx, 512, 512, 392)
    ctx.set_source_rgb(*RED)
    ctx.set_line_width(62)
    ctx.stroke()

    glyph(ctx, "A", 520, 512, 512, color=RED, weight=22)


VARIANTS = {
    "seal": variant_seal,
    "wordmark": variant_wordmark,
    "monogram": variant_monogram,
}


def render(name):
    surface, ctx = canvas()
    background(ctx)
    VARIANTS[name](ctx)
    surface.flush()

    tmp = os.path.join(HERE, f".{name}.tmp.png")
    surface.write_to_png(tmp)

    full = Image.open(tmp).convert("RGB")
    full = full.resize((BASE, BASE), Image.LANCZOS)
    full.save(os.path.join(HERE, f"icon-{name}-1024.png"), optimize=True)

    for size in (512, 128):
        full.resize((size, size), Image.LANCZOS).save(
            os.path.join(HERE, f"icon-{name}-{size}.png"), optimize=True
        )

    os.remove(tmp)
    return full


if __name__ == "__main__":
    images = {name: render(name) for name in VARIANTS}

    # the seal is the one to use, also written without a variant name in it
    primary = images["seal"]
    for size in (1024, 512, 128):
        name = "icon.png" if size == 1024 else f"icon-{size}.png"
        target = os.path.join(HERE, name)
        primary.resize((size, size), Image.LANCZOS).save(target, optimize=True)

    # one sheet, three variants stacked, 512 / 128 / 64 in a row
    cols = 512 + 128 + 64 + 80
    sheet = Image.new("RGB", (cols, 512 * len(images)), (16, 16, 18))

    for row, (name, img) in enumerate(images.items()):
        top = row * 512
        sheet.paste(img.resize((512, 512), Image.LANCZOS), (0, top))
        sheet.paste(img.resize((128, 128), Image.LANCZOS), (528, top + 16))
        sheet.paste(img.resize((64, 64), Image.LANCZOS), (680, top + 16))

    sheet.save(os.path.join(HERE, "sheet.png"), optimize=True)
    print("wrote", ", ".join(sorted(f for f in os.listdir(HERE) if f.startswith("icon-") or f == "sheet.png")))
